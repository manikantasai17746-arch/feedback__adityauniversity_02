"""Unit tests for the SQLite -> PostgreSQL translation layer.

These run without a Postgres server: they verify that every construct the app
relies on is rewritten correctly, and that every migration statement survives
the translation (the strongest guard that Supabase migrations will succeed).
"""
import pytest

from feedback_system import db, pg
from feedback_system.schema import MIGRATIONS


def test_is_postgres_url():
    assert pg.is_postgres_url('postgres://user:pw@host:6543/postgres')
    assert pg.is_postgres_url('postgresql://user:pw@host:5432/postgres?sslmode=require')
    assert pg.is_postgres_url('POSTGRESQL://host/db')
    assert not pg.is_postgres_url('feedback.db')
    assert not pg.is_postgres_url('/tmp/test.db')
    assert not pg.is_postgres_url(None)
    assert not pg.is_postgres_url('')


def test_autoincrement_becomes_identity():
    sql = 'id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT'
    out = pg.to_postgres(sql)
    assert 'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in out
    assert 'AUTOINCREMENT' not in out


def test_bare_integer_primary_key_becomes_identity():
    sql = 'id INTEGER PRIMARY KEY, roll TEXT, course_code TEXT'
    out = pg.to_postgres(sql)
    assert 'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in out
    assert 'AUTOINCREMENT' not in out


def test_current_timestamp_default_uses_iso_text():
    out = pg.to_postgres("created TEXT DEFAULT CURRENT_TIMESTAMP")
    assert 'to_char' in out and 'CURRENT_TIMESTAMP' not in out
    assert 'T' in out  # ISO 'T' separator


def test_insert_or_ignore_becomes_on_conflict():
    out = pg.to_postgres('INSERT OR IGNORE INTO t(a, b) VALUES(?, ?)')
    assert out.upper().startswith('INSERT INTO')
    assert 'OR IGNORE' not in out.upper()
    assert out.rstrip().endswith('ON CONFLICT DO NOTHING')
    assert '?' not in out and out.count('%s') == 2


def test_insert_or_ignore_multiline_select():
    sql = ('INSERT OR IGNORE INTO form_sessions(form_id, session_id)\n'
           '    SELECT id, session_id FROM feedback_forms WHERE session_id IS NOT NULL')
    out = pg.to_postgres(sql)
    assert 'OR IGNORE' not in out.upper()
    assert out.rstrip().endswith('ON CONFLICT DO NOTHING')


def test_create_view_if_not_exists():
    out = pg.to_postgres('CREATE VIEW IF NOT EXISTS anonymous_answers AS SELECT 1')
    assert out.upper().startswith('CREATE OR REPLACE VIEW')


def test_add_column_if_not_exists():
    out = pg.to_postgres('ALTER TABLE feedback_forms ADD COLUMN scope TEXT')
    assert 'ADD COLUMN IF NOT EXISTS' in out
    # must not double-apply
    assert 'IF NOT EXISTS IF NOT EXISTS' not in pg.to_postgres(out)


def test_like_becomes_ilike_and_placeholders():
    out = pg.to_postgres("SELECT * FROM users WHERE name LIKE ? OR roll LIKE ?")
    assert out.count('ILIKE') == 2
    assert '?' not in out and out.count('%s') == 2


def test_with_returning_is_idempotent():
    sql = 'INSERT INTO feedback_forms(title) VALUES(%s)'
    once = pg.with_returning(sql)
    assert once.rstrip().endswith('RETURNING id')
    assert pg.with_returning(once).rstrip().endswith('RETURNING id')
    assert pg.with_returning(once).lower().count('returning') == 1


def test_row_supports_index_and_name():
    row = pg.Row({'a': 1, 'b': 'x'}, ['a', 'b'])
    assert row[0] == 1 and row[1] == 'x'
    assert row['a'] == 1 and row['b'] == 'x'
    assert list(row.keys()) == ['a', 'b']
    assert dict(row) == {'a': 1, 'b': 'x'}
    assert 'a' in row and row.get('missing', 9) == 9
    assert list(row) == [1, 'x']


@pytest.mark.parametrize('statement', [s for _v, _d, stmts in MIGRATIONS for s in stmts])
def test_every_migration_statement_translates(statement):
    out = pg.to_postgres(statement)
    assert '?' not in out, 'qmark placeholder survived translation'
    assert 'AUTOINCREMENT' not in out.upper()
    assert 'INSERT OR IGNORE' not in out.upper()
    assert 'CREATE VIEW IF NOT EXISTS' not in out.upper()
    assert 'DEFAULT CURRENT_TIMESTAMP' not in out.upper()
    assert ' ADD COLUMN ' not in out.upper() or 'ADD COLUMN IF NOT EXISTS' in out.upper()


def test_sqlite_target_is_not_postgres(app):
    with app.app_context():
        assert not db.using_postgres()
        assert db.database_target().endswith('.db')
